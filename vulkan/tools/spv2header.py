#!/usr/bin/env python3
"""Turns a .spv binary into a uint32_t array inside a C header.

Usage:
    python tools/spv2header.py --out native/src/lime_vulkan_triangle_spirv.h \
        kTriangleVertexSpirv=native/shaders/out/triangle.vert.spv \
        kTriangleFragmentSpirv=native/shaders/out/triangle.frag.spv
"""

import argparse
import struct
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", required=True)
    parser.add_argument("pairs", nargs="+", help="NAME=path.spv")
    args = parser.parse_args()

    # The include guard follows the output file name, so the name of the header
    # and the guard can never drift apart.
    guard = "".join(ch if ch.isalnum() else "_" for ch in Path(args.out).stem).upper()

    lines = ["// Generated by tools/spv2header.py, do not edit.", "// Source: native/shaders/*.vert/.frag -> glslangValidator -> SPIR-V", "#ifndef " + guard, "#define " + guard, "", "#include <stdint.h>", ""]

    for pair in args.pairs:
        name, path = pair.split("=", 1)
        data = Path(path).read_bytes()

        # SPIR-V is 4 byte aligned; some tools append a newline, so trim before validating
        if len(data) % 4 != 0:
            data = data.rstrip(b"\n\r\0")

        if len(data) % 4 != 0:
            print(f"error: {path} size {len(data)} is not a multiple of 4")
            return 1

        words = struct.unpack(f"<{len(data) // 4}I", data)
        lines.append(f"static const uint32_t {name}[] = {{")
        for index in range(0, len(words), 6):
            chunk = ", ".join(f"0x{word:08x}u" for word in words[index:index + 6])
            lines.append(f"\t{chunk},")
        lines.append("};")
        lines.append("")

    lines.append("#endif")
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
